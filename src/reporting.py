"""Incident report export (Markdown + JSON): summary, MITRE chain, timeline, affected resources, recommended response."""
from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[1]
_RESOURCE_KEYS = {"bucketName": "S3 bucket", "userName": "IAM user", "roleName": "IAM role", "functionName": "Lambda function",
                  "policyArn": "IAM policy", "snapshotId": "EBS snapshot", "groupId": "Security group", "name": "CloudTrail trail",
                  "trailName": "CloudTrail trail", "detectorId": "GuardDuty detector", "instanceType": "Instance type", "secretId": "Secret"}


def load_playbook() -> dict:
    return yaml.safe_load((ROOT / "config" / "response_playbook.yaml").read_text(encoding="utf-8"))


def affected_resources(raw_events: list[dict]) -> dict[str, list[str]]:
    """Pull resource identifiers out of request/response parameters of the given CloudTrail records."""
    found: dict[str, set] = {}

    def add(kind: str, val: Any) -> None:
        if isinstance(val, str) and val:
            found.setdefault(kind, set()).add(val)

    for rec in raw_events:
        rp = rec.get("requestParameters") or {}
        for k, kind in _RESOURCE_KEYS.items():
            if k in rp:
                add(kind, rp[k])
        for it in ((rp.get("instancesSet") or {}).get("items") or []):
            add("EC2 instance", it.get("instanceId"))
        for it in (((rec.get("responseElements") or {}).get("instancesSet") or {}).get("items") or []):
            add("EC2 instance", it.get("instanceId"))
        perm = ((rp.get("createVolumePermission") or {}).get("add") or {}).get("items") or []
        for it in perm:
            add("External account", it.get("userId"))
        ak = ((rec.get("responseElements") or {}).get("accessKey") or {}).get("accessKeyId")
        add("Access key created", ak)
    return {k: sorted(v) for k, v in sorted(found.items())}


def recommended_steps(techniques: list[str], tactics: list[str]) -> list[str]:
    pb = load_playbook()
    steps: list[str] = []
    for t in techniques:
        for s in pb["by_technique"].get(t, []):
            if s not in steps:
                steps.append(s)
    for t in tactics:
        for s in pb["by_tactic"].get(t, []):
            if s not in steps:
                steps.append(s)
    for s in pb["generic"]:
        if s not in steps:
            steps.append(s)
    return steps


def build_report(incident: dict, alerts: list[dict], timeline: list[dict], raw_events: list[dict], notes: str = "") -> dict:
    """incident/alerts are DB rows (dicts); timeline = [{time, identity, ip, event, region, error, risk}] sorted by time."""
    res = affected_resources(raw_events)
    steps = recommended_steps(incident.get("techniques") or [], incident.get("tactics") or [])
    return {
        "incident_id": incident["incident_id"], "title": incident["title"], "severity": incident["severity"],
        "risk_score": incident["risk_score"], "status": incident["status"], "first_seen": str(incident["first_seen"]),
        "last_seen": str(incident["last_seen"]), "identities": incident["identities"], "source_ips": incident["ips"],
        "mitre_tactics": incident["tactics"], "mitre_techniques": incident["techniques"], "detection_sources": incident["sources"],
        "analyst_notes": notes, "alerts": alerts, "timeline": timeline, "affected_resources": res, "recommended_response": steps,
        "generated_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "disclaimer": "Generated by cloud-threat-detection. Detections are heuristic; verify before acting.",
    }


def to_markdown(rep: dict) -> str:
    L = [f"# Incident {rep['incident_id']}: {rep['title']}", ""]
    L += [f"- **Severity:** {rep['severity']} (risk score {rep['risk_score']})", f"- **Status:** {rep['status']}",
          f"- **Window:** {rep['first_seen']} to {rep['last_seen']} (UTC)",
          f"- **Identities:** {', '.join(rep['identities'])}", f"- **Source IPs:** {', '.join(rep['source_ips']) or 'n/a'}",
          f"- **Detected by:** {', '.join(rep['detection_sources'])}", ""]
    L += ["## Summary", ""]
    chain = " → ".join(rep["mitre_tactics"]) if rep["mitre_tactics"] else "n/a"
    L += [f"{len(rep['alerts'])} alert(s) were grouped into this incident. MITRE ATT&CK tactic chain: **{chain}**.", ""]
    if rep["mitre_techniques"]:
        L += ["Techniques: " + ", ".join(rep["mitre_techniques"]), ""]
    L += ["## Alerts", "", "| Time (UTC) | Severity | Source | Title | Identity | Detail |", "|---|---|---|---|---|---|"]
    for a in rep["alerts"]:
        L.append(f"| {a['detected_at']} | {a['severity']} | {a['source']} | {a['title']} | {a['identity']} | {str(a.get('detail') or '').replace('|', '/')} |")
    why = [a for a in rep["alerts"] if a.get("reasons")]
    if why:
        L += ["", "## Why the anomaly model flagged it", ""]
        for a in why:
            rs = a["reasons"] if isinstance(a["reasons"], list) else json.loads(a["reasons"])
            L.append(f"- {a['identity']} @ {a['detected_at']}: " + ", ".join(f"`{r['feature']}={r['value']}` ({r['contribution']:+.2f})" for r in rs))
    L += ["", "## Timeline", "", "| Time (UTC) | Identity | Source IP | Event | Region | Result | Flagged |", "|---|---|---|---|---|---|---|"]
    for t in rep["timeline"][:200]:
        L.append(f"| {t['time']} | {t['identity']} | {t['ip']} | {t['event']} | {t['region']} | {t['error'] or 'ok'} | {t['risk']} |")
    if len(rep["timeline"]) > 200:
        L.append(f"| … | | | {len(rep['timeline']) - 200} more events in the JSON export | | | |")
    L += ["", "## Affected resources", ""]
    L += [f"- **{k}:** {', '.join(v)}" for k, v in rep["affected_resources"].items()] or ["- none extracted"]
    L += ["", "## Recommended response", ""] + [f"{i}. {s}" for i, s in enumerate(rep["recommended_response"], 1)]
    if rep["analyst_notes"]:
        L += ["", "## Analyst notes", "", rep["analyst_notes"]]
    L += ["", "---", f"*{rep['disclaimer']} Generated {rep['generated_at']}.*", ""]
    return "\n".join(L)
